// Builds the chart of accounts the app starts every company from, out of scripts/chart-data.mjs:
//   db/seed.sql        groups, subgroups (with their roles) and the generic settings: the same for every company
//   db/charts/<T>.sql  the accounts of one business template (C, W, I, P, K), the bank accounts they start
//                      with and the settings that point at them
// A company's database is filled from seed.sql, then its template's chart, then its own profile (db/profiles).
//   node scripts/build-chart.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { TEMPLATES, SECTIONS, SUBGROUPS, A, GROUP_NO, GROUP_NAME, SUBGROUP_NO, NEW_NO } from "./chart-data.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const dbDir = path.join(root, "db");
const q = (v) => (v === undefined || v === null || v === "" ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

// ---- seed.sql ----
const groups = Object.keys(GROUP_NO).map((k) => {
  const sec = SECTIONS.find((s) => s.key === k);
  return `(${GROUP_NO[k]}, ${q(GROUP_NAME[k])}, ${q(sec.statement === "Profit & loss" ? "P&L" : "Balance Sheet")})`;
});
const subgroups = SUBGROUPS.map((sg) => `(${SUBGROUP_NO[sg.key]}, ${q(sg.name)}, ${GROUP_NO[sg.section]}, ${q(sg.normal)}, ${q(sg.role)})`);
const seed = `-- Generated by scripts/build-chart.mjs from scripts/chart-data.mjs. Do not edit by hand.
INSERT INTO account_groups (group_no, name, statement) VALUES
${groups.join(",\n")};

INSERT INTO account_subgroups (subgroup_no, name, group_no, normal_balance, role) VALUES
${subgroups.join(",\n")};

INSERT INTO app_settings
  (id, company_name, currency, date_format, fiscal_year_start_month, reporting_year,
   first_invoice_number, invoice_prefix, invoice_suffix, payment_term_days, payment_term_reminder_days,
   validity_period_offer_days, vat_rate_1, vat_rate_2, vat_rate_3, age_analysis_1_days, age_analysis_2_days, age_analysis_3_days)
VALUES
  (1, 'New company', '€', 'dd-mmm-yyyy', 1, EXTRACT(YEAR FROM now())::int,
   1, 'INV', '-' || EXTRACT(YEAR FROM now())::int, 14, 7,
   60, 0.23, 0.13, 0.06, 30, 60, 90);
`;
fs.mkdirSync(dbDir, { recursive: true });
fs.writeFileSync(path.join(dbDir, "seed.sql"), seed, "utf8");

// ---- one chart per template ----
const byRole = (letter, role) => A.find((a) => a[6].includes(letter) && a[7] === role)?.[0];
fs.mkdirSync(path.join(dbDir, "charts"), { recursive: true });
for (const [letter, label] of Object.entries(TEMPLATES)) {
  const accounts = A.filter((a) => a[6].includes(letter)).sort((x, y) => x[0] - y[0]);
  const ref = (role) => {
    const no = byRole(letter, role);
    if (no == null) throw new Error(`template ${letter} has no ${role} account`);
    return no;
  };
  const sales = ref("default_sales");
  const banks = [
    ["BANK1", "Bank account 1", NEW_NO[1210], false],
    ...(letter === "K" ? [] : [["BANK2", "Bank account 2", NEW_NO[1220], false]]),
    ...(letter === "K" ? [] : [["CASH", "Petty cash", NEW_NO[1110], true]]),
  ];
  // Accounts the entry forms must not post to directly: the ledgers the app maintains itself.
  const reserved = [ref("accounts_receivable"), ref("accounts_payable"), ref("vat_output"), ref("vat_input"), ...banks.map((b) => b[2])];
  const interest = byRole(letter, "interest_expense");
  const sql = `-- Generated by scripts/build-chart.mjs: chart for the ${label} template (${letter}). Do not edit by hand.
INSERT INTO accounts (account_no, name, subgroup_no, role) VALUES
${accounts.map((a) => `(${a[0]}, ${q(a[1])}, ${SUBGROUP_NO[a[3]]}, ${q(a[7])})`).join(",\n")};

UPDATE app_settings SET
  account_no_ar = ${ref("accounts_receivable")}, account_no_ap = ${ref("accounts_payable")}, account_no_sales = ${sales},
  account_no_sales_tax_payable = ${ref("vat_output")}, account_no_purchase_tax_payable = ${ref("vat_input")},
  account_no_vat_paid_received = ${ref("vat_settlement")}, account_no_interest_expense = ${interest ?? "NULL"}
WHERE id = 1;

INSERT INTO bank_accounts (key, name, account_no, is_cash) VALUES
${banks.map((b) => `('${b[0]}', ${q(b[1])}, ${b[2]}, ${b[3]})`).join(",\n")};

UPDATE accounts SET is_reserved = true WHERE account_no IN (${reserved.join(", ")});
`;
  fs.writeFileSync(path.join(dbDir, "charts", `${letter}.sql`), sql, "utf8");
}
console.log(`wrote db/seed.sql and ${Object.keys(TEMPLATES).length} charts`);
